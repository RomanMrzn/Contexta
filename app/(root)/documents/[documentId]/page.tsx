"use client";

import { useChat } from "@ai-sdk/react";
import { Send, Bot, User, FileText, Download } from "lucide-react";
import { useParams } from "next/navigation";

export default function DocumentDetailPage() {
  const params = useParams();
  const documentId = params.documentId as string;
  
  const { messages, input, handleInputChange, handleSubmit, isLoading } = useChat({
    api: "/api/chat",
    body: { documentId },
  });

  return (
    <div className="max-w-6xl mx-auto h-[calc(100vh-8rem)] flex gap-6">
      {/* Left side - Document Summary/Viewer */}
      <div className="w-1/3 bg-neutral-950 border border-neutral-800 rounded-xl flex flex-col overflow-hidden">
        <div className="p-6 border-b border-neutral-800 bg-neutral-900/50">
          <div className="flex items-center gap-3">
            <div className="p-2 bg-indigo-500/10 rounded-md">
              <FileText className="w-6 h-6 text-indigo-400" />
            </div>
            <div>
              <h2 className="font-bold text-white truncate" title="Document Title">Document Title</h2>
              <p className="text-xs text-neutral-500">ID: {documentId}</p>
            </div>
          </div>
        </div>
        
        <div className="flex-1 p-6 overflow-y-auto">
          <h3 className="text-sm font-semibold text-neutral-400 uppercase tracking-wider mb-3">AI Summary</h3>
          <div className="prose prose-invert prose-sm">
            <p className="text-neutral-300">
              This document's summary will appear here once generated by the AI processing pipeline. 
              The system analyzes the entire text and produces a concise overview of the contents.
            </p>
          </div>
        </div>

        <div className="p-4 border-t border-neutral-800 bg-neutral-900/30">
          <button className="w-full py-2 bg-neutral-800 hover:bg-neutral-700 text-neutral-200 rounded-lg flex items-center justify-center gap-2 transition-colors">
            <Download className="w-4 h-4" />
            Download Original
          </button>
        </div>
      </div>

      {/* Right side - Chat */}
      <div className="flex-1 bg-neutral-950 border border-neutral-800 rounded-xl flex flex-col overflow-hidden">
        <div className="p-6 border-b border-neutral-800 bg-neutral-900/50">
          <h2 className="text-lg font-bold text-white">Chat with Document</h2>
        </div>

        <div className="flex-1 overflow-y-auto p-6 space-y-6">
          {messages.length === 0 ? (
            <div className="h-full flex flex-col items-center justify-center text-center space-y-4 text-neutral-500">
              <Bot className="w-10 h-10 text-neutral-700" />
              <p>Ask anything specifically about this document.</p>
            </div>
          ) : (
            messages.map((m) => (
              <div key={m.id} className={`flex gap-4 ${m.role === "user" ? "justify-end" : "justify-start"}`}>
                {m.role !== "user" && (
                  <div className="w-8 h-8 rounded-full bg-indigo-500/20 flex items-center justify-center flex-shrink-0">
                    <Bot className="w-4 h-4 text-indigo-400" />
                  </div>
                )}
                <div className={`max-w-[80%] rounded-2xl px-4 py-2 text-sm ${m.role === "user" ? "bg-indigo-600 text-white" : "bg-neutral-800 text-neutral-200"}`}>
                  <p className="whitespace-pre-wrap">{m.content}</p>
                </div>
              </div>
            ))
          )}
          {isLoading && (
             <div className="flex gap-4 justify-start">
               <div className="w-8 h-8 rounded-full bg-indigo-500/20 flex items-center justify-center flex-shrink-0">
                 <Bot className="w-4 h-4 text-indigo-400" />
               </div>
               <div className="max-w-[80%] rounded-2xl px-4 py-2 bg-neutral-800 text-neutral-200 flex items-center">
                  <div className="flex space-x-1.5">
                    <div className="w-1.5 h-1.5 rounded-full bg-neutral-500 animate-bounce" />
                    <div className="w-1.5 h-1.5 rounded-full bg-neutral-500 animate-bounce" style={{ animationDelay: '0.2s' }} />
                    <div className="w-1.5 h-1.5 rounded-full bg-neutral-500 animate-bounce" style={{ animationDelay: '0.4s' }} />
                  </div>
               </div>
             </div>
          )}
        </div>

        <div className="p-4 bg-neutral-900 border-t border-neutral-800">
          <form onSubmit={handleSubmit} className="flex gap-3">
            <input
              type="text"
              value={input}
              onChange={handleInputChange}
              placeholder="Ask a question..."
              className="flex-1 bg-neutral-950 border border-neutral-800 text-white text-sm rounded-lg px-4 py-3 focus:outline-none focus:ring-2 focus:ring-indigo-500 transition-all"
              disabled={isLoading}
            />
            <button
              type="submit"
              disabled={isLoading || !input.trim()}
              className="bg-indigo-600 hover:bg-indigo-700 disabled:bg-neutral-800 text-white rounded-lg px-5 flex items-center justify-center transition-colors"
            >
              <Send className="w-4 h-4" />
            </button>
          </form>
        </div>
      </div>
    </div>
  );
}
